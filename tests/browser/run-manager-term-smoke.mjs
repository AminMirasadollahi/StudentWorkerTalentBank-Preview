/* SWTB20 one isolated native Chrome UX and accounting smoke; zero real API calls. */
import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {resolve} from 'node:path'
import {createServer} from 'vite'
import {chromium} from 'playwright'

const output=resolve('test-results/swtb20-manager-dialogs')
await mkdir(output,{recursive:true})
let server,browser,page
let blocked=0
const pageErrors=[]
try{
 server=await createServer({configFile:resolve('tests/browser/vite.smoke.config.mjs')})
 await server.listen()
 browser=await chromium.launch({headless:true,channel:'chrome',args:['--no-sandbox']})
 page=await browser.newPage({viewport:{width:1440,height:900},locale:'fa-IR'})
 page.on('pageerror',error=>pageErrors.push(error.message))
 await page.route('**/*',route=>{
  const url=new URL(route.request().url())
  if(url.hostname==='127.0.0.1'||url.hostname==='localhost')return route.continue()
  blocked++
  return route.abort('blockedbyclient')
 })
 await page.goto('http://127.0.0.1:4177/tests/browser/manager-term-smoke.html',{waitUntil:'domcontentloaded'})
 await page.getByRole('heading',{name:'نیمسال‌ها و سهمیه ساعات'}).waitFor()
 assert.ok((await page.locator('.ow-term-status-explainer').innerText()).includes('پیش‌نویس'))
 assert.equal(await page.getByRole('button',{name:'فعال‌سازی نیمسال'}).isDisabled(),true)
 await page.getByRole('button',{name:'+ تعریف سهمیه'}).click()
 let modal=page.getByRole('dialog',{name:'تعریف سهمیه مصوب'})
 await modal.waitFor({state:'visible'})
 await modal.getByRole('checkbox',{name:'کتابخانه'}).check()
 await modal.getByRole('checkbox',{name:'پژوهش'}).check()
 assert.ok((await modal.locator('.ow-pool-preview').innerText()).includes('کتابخانه و پژوهش'))
 assert.equal(await modal.locator('[aria-label="دقیقه گروه سهمیه"]').count(),0)
 assert.equal(await modal.getByText('علت اصلاح سهمیه').count(),0)
 await modal.getByRole('textbox',{name:'سهمیه مصوب به ساعت'}).fill('۴۱۱')
 assert.equal(await modal.getByRole('button',{name:'ثبت سهمیه'}).isDisabled(),false)
 await page.screenshot({path:resolve(output,'01-hour-only-shared-pool-modal.png'),fullPage:true})
 await modal.getByRole('button',{name:'ثبت سهمیه'}).click()
 await modal.waitFor({state:'hidden'})
 let writes=await page.evaluate(()=>globalThis.__qaTermWrites)
 assert.equal(writes.length,1)
 assert.deepEqual(writes[0].units,['library','research'])
 assert.equal(writes[0].minutes,24660)
 assert.match(writes[0].reason,/خودکار/)
 await page.getByRole('button',{name:'+ تعریف سهمیه'}).click()
 modal=page.getByRole('dialog',{name:'تعریف سهمیه مصوب'})
 await modal.getByRole('checkbox',{name:'روابط عمومی'}).check()
 await modal.getByRole('textbox',{name:'سهمیه مصوب به ساعت'}).fill('۱۰۰')
 await modal.getByRole('button',{name:'ثبت سهمیه'}).click()
 await modal.waitFor({state:'hidden'})
 writes=await page.evaluate(()=>globalThis.__qaTermWrites)
 assert.equal(writes.length,2)
 assert.equal(writes[1].minutes,6000)
 assert.equal(writes[1].label,'روابط عمومی')
 await page.screenshot({path:resolve(output,'02-two-pools-511h-overview.png'),fullPage:true})
 await page.getByRole('button',{name:'ویرایش نیمسال'}).click()
 modal=page.getByRole('dialog',{name:'ویرایش مشخصات نیمسال'})
 await modal.waitFor({state:'visible'})
 assert.equal(await modal.getByText('علت اصلاح مشخصات').count(),0)
 await modal.getByRole('button',{name:'تاریخ پایان نیمسال'}).click()
 await modal.locator('.jd-popup').waitFor({state:'visible'})
 await page.screenshot({path:resolve(output,'03-jalali-picker-inside-modal.png'),fullPage:true})
 await page.keyboard.press('Escape')
 await modal.locator('.jd-popup').waitFor({state:'hidden'})
 assert.equal(await modal.isVisible(),true,'Esc in date picker must keep parent modal open')
 await page.keyboard.press('Escape')
 await modal.waitFor({state:'hidden'})
 await page.getByRole('button',{name:'فعال‌سازی نیمسال'}).click()
 modal=page.getByRole('dialog',{name:'تأیید و فعال‌سازی نیمسال'})
 await modal.waitFor({state:'visible'})
 assert.ok((await modal.innerText()).includes('کتابخانه و پژوهش'))
 assert.equal(await modal.getByRole('button',{name:'فعال‌سازی قطعی نیمسال'}).isDisabled(),true)
 await page.screenshot({path:resolve(output,'04-explicit-activation-confirmation.png'),fullPage:true})
 assert.equal((await page.evaluate(()=>globalThis.__qaTermWrites)).length,2,'status must not change without confirmation')
 assert.equal(pageErrors.length,0,'page JS errors: '+pageErrors.join('; '))
 assert.equal(blocked,0,'no outside network requests permitted')
 process.stdout.write('PASS SWTB20 native Chrome: 411+100 exact hours, modal/date picker focus and explicit activation; synthetic only\n')
}finally{
 await page?.close().catch(()=>{})
 await browser?.close().catch(()=>{})
 await server?.close().catch(()=>{})
}
