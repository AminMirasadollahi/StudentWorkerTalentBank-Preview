import test from 'node:test'
import assert from 'node:assert/strict'
import {buildDayBatchPlan,prepareDayBatchIntent,batchReserveArgs,batchCommitArgs,batchDiscoverArgs,parseDayBatchSnapshot,batchControlArgs,parseDayBatchControlResult} from '../src/lib/dayBatchAssignmentContract.mjs'
const id=n=>'20000000-0000-4000-8000-'+String(n).padStart(12,'0')
const a=id(1),b=id(2),term=id(3),key=id(4),pre=id(5),ep=7
const ctx=()=>({today:'2026-11-27',term:{id:term,state:'active',start_date:'2026-09-23',end_date:'2027-02-09'},workers:[{id:a,state:'active'},{id:b,state:'active'}],data:{tasks:[{id:pre,worker_id:a,planned_date:'2026-12-01',estimate_minutes:30,state:'assigned'}],weekly_slots:[],exceptions:[]}})
const row=(id,workerIds,more={})=>({id,title:'کار نمونه',instructions:'شرح نمونه',minutes:45,mode:'independent',workerIds,date:null,unit:null,reason:null,prerequisiteIds:[],...more})
const draft=(rows)=>({termId:term,defaults:{date:'2026-12-01',unit:'library',reason:''},rows})
const example=()=>buildDayBatchPlan(draft([row('z',[a,b],{mode:'collaborative',minutes:60}),row('A',[a],{prerequisiteIds:[pre]})]),ctx())
const recovery=(active=null,epoch=ep,durable_active=false)=>({ok:true,epoch,active,durable_active})
const read=(raw,intent=null)=>parseDayBatchSnapshot(raw,{source:'discover',intent})
const idle=()=>read(recovery())
const setup=()=>prepareDayBatchIntent(example(),key,idle())
const active=(status='reserved',receipt)=>({kind:'batch_direct_v1',request_id:key,status,...(status==='committed'?{receipt}: {})})
const written=(status='reserved',receipt)=>({ok:true,epoch:ep,active:active(status,receipt)})
const validReceipt=()=>({ok:true,request_id:key,kind:'batch_direct_v1',result:{term_id:term,rows:[{row_id:'A',mode:'independent',group_id:null,minutes_per_worker:45,tasks:[{worker_id:a,task_id:id(10)}]},{row_id:'z',mode:'collaborative',group_id:id(11),minutes_per_worker:60,tasks:[{worker_id:a,task_id:id(12)},{worker_id:b,task_id:id(13)}]}],pair_count:3,standard_person_minutes:165}})
const clone=x=>JSON.parse(JSON.stringify(x))
test('exact explicit matrix and per-person totals; stable canonical row order; immutable',()=>{
 const input=draft([row('z',[b,a],{mode:'collaborative',minutes:60}),row('A',[a],{prerequisiteIds:[pre]})]),before=JSON.stringify(input)
 const p=buildDayBatchPlan(input,ctx())
 assert.equal(JSON.stringify(input),before);assert.equal(p.pairCount,3);assert.equal(p.standardPersonMinutes,165)
 assert.deepEqual(p.rows.map(x=>x.id),['A','z']);assert.deepEqual(p.rows[0].worker_ids,[a]);assert.deepEqual(p.rows[1].worker_ids,[a,b])
 assert.deepEqual(p.rows[0].prerequisites,[pre]);assert.equal(p.rows[0].date,'2026-12-01')
 assert.equal(Object.isFrozen(p.rows[0].worker_ids),true)
 assert.equal(Object.hasOwn(p.rows[0],'p_request_id'),false)
})
test('independent multiple recipients stay one explicit row, not a collaborative group',()=>{
 const p=buildDayBatchPlan(draft([row('one',[b,a])]),ctx())
 assert.equal(p.rows.length,1);assert.equal(p.rows[0].mode,'independent');assert.deepEqual(p.rows[0].worker_ids,[a,b]);assert.equal(p.standardPersonMinutes,90)
})
test('reject invalid row id, 21 rows, invalid term, unapproved split and preview validation failure',()=>{
 assert.throws(()=>buildDayBatchPlan(draft([row('bad id',[a])]),ctx()),/BATCH_ROW_ID_INVALID/)
 assert.throws(()=>buildDayBatchPlan(draft(Array.from({length:21},(_,i)=>row('r'+i,[a]))),ctx()),/BATCH_CONTRACT_LIMIT_OR_TERM/)
 const x=ctx();x.term.id='term-1';assert.throws(()=>buildDayBatchPlan({...draft([row('x',[a])]),termId:'term-1'},x),/BATCH_CONTRACT_LIMIT_OR_TERM/)
 assert.throws(()=>buildDayBatchPlan(draft([row('x',[a],{mode:'split'})]),ctx()),/BATCH_PREVIEW_INVALID/)
 assert.throws(()=>buildDayBatchPlan(draft([row('x',[a],{minutes:0})]),ctx()),/BATCH_PREVIEW_INVALID/)
})
test('reject >80 pairs; 80 explicit pairs allowed in review',()=>{
 const x=ctx();x.workers=Array.from({length:81},(_,i)=>({id:id(100+i),state:'active'}))
 const ids=x.workers.map(w=>w.id)
 assert.throws(()=>buildDayBatchPlan(draft([row('one',ids)]),x),/BATCH_CONTRACT_LIMIT_OR_TERM/)
 assert.equal(buildDayBatchPlan(draft([row('one',ids.slice(0,80))]),x).pairCount,80)
})
test('fresh validated discovery required; durable or foreign is not idle; untrusted plans denied',()=>{
 const p=example()
 assert.throws(()=>prepareDayBatchIntent({...p},key,idle()),/BATCH_INTENT_INVALID/)
 assert.throws(()=>prepareDayBatchIntent(p,key,{state:'idle',epoch:ep}),/BATCH_INTENT_INVALID/)
 assert.equal(read(recovery(null,ep,true)).state,'held')
 assert.throws(()=>prepareDayBatchIntent(p,key,read(recovery(null,ep,true))),/BATCH_INTENT_INVALID/)
 const f=read(recovery({kind:'direct',status:'reserved',foreign:true}))
 assert.equal(f.state,'foreign');assert.throws(()=>prepareDayBatchIntent(p,key,f),/BATCH_INTENT_INVALID/)
 assert.throws(()=>batchControlArgs('cancel',f),/BATCH_CONTROL_INVALID/)
 assert.deepEqual(batchDiscoverArgs(),{p_action:'discover',p_epoch:null,p_request_id:null})
})
test('commit requires same in-memory intent and confirmed reserve; no guessed reload commit',()=>{
 const i=setup(),reserve=batchReserveArgs(i)
 assert.deepEqual(Object.keys(reserve),['p_action','p_epoch','p_request_id','p_term_id','p_rows'])
 assert.throws(()=>batchCommitArgs(i,read(recovery(active()))),/BATCH_RESERVE_NOT_CONFIRMED/)
 assert.throws(()=>batchCommitArgs(i,{state:'reserved',epoch:ep,requestId:key}),/BATCH_RESERVE_NOT_CONFIRMED/)
 const s=parseDayBatchSnapshot(written(),{source:'write',intent:i})
 assert.equal(s.state,'reserved');assert.equal(Object.hasOwn(s,'intent'),false)
 assert.deepEqual(batchCommitArgs(i,s),{...reserve,p_action:'commit'})
 assert.throws(()=>batchCommitArgs(setup(),s),/BATCH_RESERVE_NOT_CONFIRMED/)
 assert.throws(()=>batchControlArgs('cancel',s),/BATCH_CONTROL_INVALID/)
})
test('write replies require exact intent key, epoch, shape and valid receipt; no raw payload leakage',()=>{
 const i=setup(),good=parseDayBatchSnapshot(written('committed',validReceipt()),{source:'write',intent:i})
 assert.equal(good.state,'committed');assert.equal(good.receipt.result.standard_person_minutes,165);assert.ok(Object.isFrozen(good.receipt.result.rows[0].tasks))
 for(const raw of [{...written(),epoch:ep+1},{...written(),active:{...active(),request_id:id(90)}},{...written(),durable_active:false},{...written(),active:null},written('committed',null)])
  assert.equal(parseDayBatchSnapshot(raw,{source:'write',intent:i}).state,'invalid')
 assert.equal(parseDayBatchSnapshot(written(),{source:'write'}).state,'invalid')
 assert.throws(()=>batchControlArgs('acknowledge',good),/BATCH_CONTROL_INVALID/)
})
test('receipt denies wrong mapping even if internally consistent, duplicate IDs, totals or extra fields',()=>{
 const i=setup(),bad=[]
 const changed=validReceipt();changed.result.rows[0].tasks[0].worker_id=b;bad.push(changed)
 const dupe=validReceipt();dupe.result.rows[1].tasks[0].task_id=id(10);bad.push(dupe)
 const total=validReceipt();total.result.standard_person_minutes=164;bad.push(total)
 const group=validReceipt();group.result.rows[0].group_id=id(99);bad.push(group)
 const extra=validReceipt();extra.result.rows[0].tasks[0].private='unexpected';bad.push(extra)
 const missing=validReceipt();missing.result.rows.pop();bad.push(missing)
 for(const r of bad)assert.equal(parseDayBatchSnapshot(written('committed',r),{source:'write',intent:i}).state,'invalid')
 // A genuine historic receipt may have a different mapping than the current draft;
 // fresh recovery validates structure, not guessed reconstruction.
 assert.equal(read(recovery(active('committed',changed))).state,'committed')
})
test('fresh recovery can cancel or acknowledge exact typed state only; mixed state always held',()=>{
 const rs=read(recovery(active())),cs=read(recovery(active('cancelled'))),done=read(recovery(active('committed',validReceipt())))
 assert.deepEqual(batchControlArgs('cancel',rs),{p_action:'cancel',p_epoch:ep,p_request_id:key})
 assert.throws(()=>batchControlArgs('acknowledge',rs),/BATCH_CONTROL_INVALID/)
 assert.throws(()=>batchControlArgs('cancel',done),/BATCH_CONTROL_INVALID/)
 assert.deepEqual(batchControlArgs('acknowledge',cs),{p_action:'acknowledge',p_epoch:ep,p_request_id:key})
 assert.deepEqual(batchControlArgs('acknowledge',done),{p_action:'acknowledge',p_epoch:ep,p_request_id:key})
 const mixed=read(recovery(active('committed',validReceipt()),ep,true));assert.equal(mixed.state,'held');assert.throws(()=>batchControlArgs('acknowledge',mixed),/BATCH_CONTROL_INVALID/)
})
test('control reply must match action, epoch and key; ack never advances twice or unlocks on uncertain result',()=>{
 const cancel=batchControlArgs('cancel',read(recovery(active())))
 const sealed=parseDayBatchControlResult(recovery(active('cancelled')),cancel)
 assert.equal(sealed.state,'cancelled')
 for(const raw of [recovery(),recovery(active('cancelled'),ep+1),recovery({...active('cancelled'),request_id:id(99)}),recovery(active('committed',validReceipt())),recovery(active('cancelled'),ep,true)])
  assert.equal(parseDayBatchControlResult(raw,cancel).state,'invalid')
 const ack=batchControlArgs('acknowledge',sealed)
 assert.equal(parseDayBatchControlResult(recovery(null,ep+1),ack).state,'idle')
 for(const raw of [recovery(null,ep),recovery(null,ep+2),recovery(active('cancelled')),recovery(null,ep+1,true)])
  assert.equal(parseDayBatchControlResult(raw,ack).state,'invalid')
 assert.equal(parseDayBatchControlResult(recovery(null,ep+1),clone(ack)).state,'invalid')
 assert.throws(()=>prepareDayBatchIntent(example(),id(99),parseDayBatchControlResult(recovery(null,ep+1),ack)),/BATCH_INTENT_INVALID/)
 assert.equal(parseDayBatchSnapshot(recovery(null,ep+1),{source:'control'}).state,'invalid')
})
test('invalid shapes and undisclosed foreign receipt never become actionable',()=>{
 for(const raw of [null,{},recovery(null,-1),recovery(null,9007199254740992),recovery({kind:'direct',status:'committed',foreign:true,receipt:{secret:true}}),recovery({kind:'batch_direct_v1',request_id:key,status:'unknown'}),recovery({kind:'batch_direct_v1',request_id:key,status:'reserved',receipt:null}),{ok:true,epoch:ep,active:null}])
  assert.equal(read(raw).state,'invalid')
 assert.throws(()=>batchControlArgs('cancel',{state:'reserved',source:'discover',epoch:ep,requestId:key}),/BATCH_CONTROL_INVALID/)
})
